describe("Minimap button", function()
    it("shows the button again on refresh when the saved settings do not hide it", function()
        WowStub.load({ minimap = { hide = false } })
        ForeverBiSMinimapButton:Hide()
        WowStub.ns.MinimapButton.refresh()
        assert.is_true(ForeverBiSMinimapButton:IsShown())
    end)

    it("stays hidden on refresh when the saved settings hide it", function()
        WowStub.load({ minimap = { hide = true } })
        WowStub.ns.MinimapButton.refresh()
        assert.is_false(ForeverBiSMinimapButton:IsShown())
    end)
end)
